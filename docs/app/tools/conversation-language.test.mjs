import test from 'node:test';
import assert from 'node:assert/strict';
import { ENGLISH_TOOL_TRIGGERS, observeConversationLanguage, applyReplyLanguage, replyLanguageLine, resolveConversationLanguage, questionLanguage } from '../js/live/conversation-language.js';
import { DEMAND_INSTRUCTIONS } from '../js/live/on-demand.js';
import { readFileSync } from 'node:fs';

test('conversation language follows a real request and ignores short replies', () => {
  assert.equal(resolveConversationLanguage({}), 'zh-CN');
  assert.equal(replyLanguageLine('zh-CN'), '');
  assert.match(replyLanguageLine('en'), /改用英文/);
  let state = observeConversationLanguage({}, 'OK');
  assert.equal(resolveConversationLanguage(state), 'zh-CN');
  state = observeConversationLanguage(state, '请用英文和我说话');
  assert.equal(state.preference, 'en');
  assert.equal(resolveConversationLanguage(state), 'en');
  state = observeConversationLanguage(state, '今天天气很好');
  assert.equal(resolveConversationLanguage(state), 'en');
  state = observeConversationLanguage(state, '请用中文和我说话');
  assert.equal(state.preference, 'zh-CN');
  assert.equal(resolveConversationLanguage(state), 'zh-CN');
  state = observeConversationLanguage({}, 'What is the weather');
  assert.equal(resolveConversationLanguage(state), 'en');
  state = observeConversationLanguage({}, 'please speak in English');
  assert.equal(state.preference, 'en');
  state = observeConversationLanguage({}, 'git clone https://example.com/demo.git');
  assert.equal(state.current, undefined);
  state = observeConversationLanguage({}, '用英文翻译这段话');
  assert.equal(state.preference, undefined);
  assert.equal(questionLanguage('what is on the screen'), 'en');
  assert.equal(questionLanguage('屏幕上有什么', 'en'), 'zh-CN');
  assert.equal(questionLanguage('cup', 'en'), 'en');
  assert.equal(questionLanguage('杯', 'zh-CN'), 'zh-CN');
});

test('an English reply removes the Chinese answer instruction', () => {
  const live = '用口语化中文回答，每次两三句话，先给结论。画面和问题有关时结合画面回答。';
  const demand = '用口语化中文回答，每次两三句话。不识别画面中人的身份。';
  assert.equal(applyReplyLanguage(live, 'zh-CN'), live);
  assert.equal(applyReplyLanguage(live), live);
  const english = applyReplyLanguage(live, 'en');
  assert.equal(english.includes('用口语化中文回答'), false);
  assert.match(english, /Answer in spoken English, in two or three sentences, and lead with the conclusion/);
  assert.match(english, /结合画面回答/);
  const demandEnglish = applyReplyLanguage(demand, 'en');
  assert.equal(demandEnglish.includes('用口语化中文回答'), false);
  assert.match(demandEnglish, /Answer in spoken English, in two or three sentences\./);
  assert.match(demandEnglish, /不识别画面中人的身份/);
  assert.match(ENGLISH_TOOL_TRIGGERS, /keep reporting my phone screen/);
  assert.match(ENGLISH_TOOL_TRIGGERS, /let me know if I cough/);
  assert.match(ENGLISH_TOOL_TRIGGERS, /hand this to the coding assistant/);
  assert.equal(DEMAND_INSTRUCTIONS.includes(ENGLISH_TOOL_TRIGGERS), true);
  const session = readFileSync(new URL('../js/pages/session.js', import.meta.url), 'utf8');
  assert.equal(session.includes('${ENGLISH_TOOL_TRIGGERS}'), true);
});
